#!/usr/bin/env node
/**
 * scripts/check-dom-refs.js — BrainzOS DOM reference smoke test
 * ============================================================================
 * Fails the build when JavaScript references DOM targets that do not exist in
 * the page markup. This class of bug previously shipped: the teacher Class
 * Assignments grid, its "+ New Assignment" modal, and two director console
 * pages were all silently broken by id drift between parallel HTML files.
 *
 * What is checked per HTML page:
 *   1. document.getElementById('literal') / getElementById("literal")
 *      -> id must exist somewhere in the markup.
 *   2. querySelector('#literal') / querySelectorAll('#literal')
 *      -> same rule.
 *   3. querySelector('.class') / querySelectorAll('.class')
 *      -> class must exist somewhere in the markup.
 *   4. id attribute duplicates within the same page.
 *
 * Deliberately NOT checked (too dynamic to assert statically):
 *   - template-literal selectors like getElementById(`badge-${id}`) — these
 *     are runtime-composed; the code already guards them with null checks.
 *   - selectors scoped to a variable (foo.querySelector(...)).
 *   - markup inside <script>/<template> blocks (not live DOM).
 *
 * Usage:
 *   node scripts/check-dom-refs.js            # checks all HTML pages
 *   node scripts/check-dom-refs.js page.html  # checks specific files
 *
 * Exit codes: 0 = clean, 1 = broken references found (fail the build).
 * ============================================================================
 */

const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..');

// Which pages to check by default. (The historical .bak snapshot copies of
// BrainzOS.html were removed from the repo on 2026-09-28; re-add any new
// snapshot to DEFAULT_GLOBS only if it is actually part of the build.)
const DEFAULT_GLOBS = [
  'index.html',
  'BrainzOS.html',
  'director.html',
  'teacher.html',
  'student.html',
  'foundation.html',
];

/** Pages that are pure redirect stubs (no inline JS to analyze). */
const REDIRECT_STUBS = new Set(['index.html', 'director.html', 'teacher.html', 'student.html']);

// Known-dead-but-harmless targets: each entry needs a one-line justification.
// These are all `A || B` fallback chains where `B` is legacy naming kept for
// older snapshots; the primary target exists and the chain is null-guarded.
const ALLOWLIST = new Set([
  // render404View fallback chain (primary id would be page-404-fallback; both absent — guarded)
  'page-404-fallback', 'unresolved-route-display',
  // mobile sidebar overlay: sidebar closes fine without it (guarded)
  'sidebar-overlay',
  // cookie banner fallback chain (primary id cookie-banner exists)
  'cookie-consent-banner',
  // command palette fallback chain (primary ids cmd-overlay/cmd-input/cmd-results-list exist)
  'command-palette-overlay', 'command-input', 'command-results',
  // legacy Pitch Pad dashboard fetches left over from the Pitch Pad removal (all guarded)
  'dash-pitch-rank', 'dash-pitch-badge', 'dash-pitch-sub',
  'total-pitch-votes-badge', 'pitch-grid-container',
  // digital pass fallback chain (primary id pass-card-element / pass-qr-canvas exist)
  'digital-pass-card', 'qr-canvas',
  // houses leaderboard fallback chain (primary ids exist; guarded)
  'house-points-nalanda', 'house-points-orion',
  'orion-house-progress-bar', 'orion-progress-bar',
  // director feed fallback chain (primary ids feed-items-container / feed-count-all exist)
  'feed-container', 'count-all',
  // runtime-generated: assignee checkboxes are injected by populateAssigneeStudentsList()
  'assignee-student-chk',
  // runtime-generated: command palette result rows are injected by filterCommandResults()
  'cmd-item',
  // runtime-generated: student dashboard promotion outcome banner injected by injectStudentDashboardPromoBanner()
  'dash-promo-banner',
  // foundation.html: sidebar/palette rows are generated by renderSidebarNav()/filterCommandResults()
  'nav-btn',
]);

// ---------------------------------------------------------------------------
// Extraction helpers
// ---------------------------------------------------------------------------

/** Pull inline <script> bodies (ignore src= scripts and JSON-LD blocks). */
function extractInlineScripts(html) {
  const blocks = [];
  const re = /<script\b([^>]*)>([\s\S]*?)<\/script>/gi;
  let m;
  while ((m = re.exec(html)) !== null) {
    const attrs = m[1] || '';
    if (/\bsrc\s*=/i.test(attrs)) continue;
    if (/\btype\s*=\s*["'](application\/(ld\+)?json|text\/template)/i.test(attrs)) continue;
    blocks.push(m[2]);
  }
  return blocks;
}

/** Markup with <script>/<style>/<template> contents removed (not live DOM). */
function extractMarkupOnly(html) {
  return html
    .replace(/<script\b[\s\S]*?<\/script>/gi, '')
    .replace(/<style\b[\s\S]*?<\/style>/gi, '')
    .replace(/<template\b[\s\S]*?<\/template>/gi, '');
}

/** All id="..." values present in the given markup fragment. */
function collectIds(markup) {
  const ids = new Set();
  const re = /\bid\s*=\s*["']([^"']+)["']/gi;
  let m;
  while ((m = re.exec(markup)) !== null) ids.add(m[1]);
  return ids;
}

/** Duplicate id="..." values (same value used on multiple elements). */
function findDuplicateIds(markup) {
  const seen = new Map();
  const re = /\bid\s*=\s*["']([^"']+)["']/gi;
  let m;
  while ((m = re.exec(markup)) !== null) {
    seen.set(m[1], (seen.get(m[1]) || 0) + 1);
  }
  return [...seen.entries()].filter(([, n]) => n > 1).map(([id]) => id);
}

/** All class="..." tokens present in the given markup fragment. */
function collectClasses(markup) {
  const classes = new Set();
  const re = /\bclass\s*=\s*["']([^"']+)["']/gi;
  let m;
  while ((m = re.exec(markup)) !== null) {
    m[1].split(/\s+/).forEach(c => { if (c) classes.add(c); });
  }
  return classes;
}

/**
 * JS selector targets referenced by the scripts, with approximate line numbers
 * resolved against the whole file (blocks are reported with their start offset).
 */
function collectJsReferences(html, inlineScripts) {
  const idRefs = new Map();   // id    -> [lineNumbers]
  const classRefs = new Map(); // class -> [lineNumbers]
  const lineStarts = [];
  {
    let idx = 0;
    for (const line of html.split('\n')) {
      lineStarts.push(idx);
      idx += line.length + 1;
    }
  }
  const lineOf = (charIndex) => {
    let lo = 0, hi = lineStarts.length - 1;
    while (lo < hi) {
      const mid = (lo + hi + 1) >> 1;
      if (lineStarts[mid] <= charIndex) lo = mid; else hi = mid - 1;
    }
    return lo + 1;
  };

  const noteRef = (map, key, charIndex) => {
    if (!key) return;
    if (!map.has(key)) map.set(key, []);
    map.get(key).push(lineOf(charIndex));
  };

  const patterns = [
    // document.getElementById('x') / ("x")
    { re: /getElementById\(\s*['"]([A-Za-z][\w-]*)['"]\s*\)/g, kind: 'id' },
    // querySelector(All)?('#x') — simple single-id selectors only
    { re: /querySelector(?:All)?\(\s*['"]#([A-Za-z][\w-]*)['"]\s*\)/g, kind: 'id' },
    // querySelector(All)?('.x') — simple single-class selectors only
    { re: /querySelector(?:All)?\(\s*['"]\.([A-Za-z][\w-]*)['"]\s*\)/g, kind: 'class' },
  ];

  for (const block of inlineScripts) {
    const blockStart = html.indexOf(block);
    for (const { re, kind } of patterns) {
      re.lastIndex = 0;
      let m;
      while ((m = re.exec(block)) !== null) {
        noteRef(kind === 'id' ? idRefs : classRefs, m[1], blockStart + m.index);
      }
    }
  }
  return { idRefs, classRefs };
}

// ---------------------------------------------------------------------------
// Per-page analysis
// ---------------------------------------------------------------------------

function checkPage(filePath) {
  const problems = [];
  const html = fs.readFileSync(filePath, 'utf8');
  const relPath = path.relative(REPO_ROOT, filePath).replace(/\\/g, '/');

  const markup = extractMarkupOnly(html);
  const ids = collectIds(markup);
  const classes = collectClasses(markup);
  const dupIds = findDuplicateIds(markup);
  const { idRefs, classRefs } = collectJsReferences(html, extractInlineScripts(html));

  // 1. getElementById / querySelector('#id') targets must exist.
  for (const [id, lines] of idRefs) {
    if (ALLOWLIST.has(id)) continue;
    if (!ids.has(id)) {
      problems.push(`MISSING ID  #${id} — referenced at line${lines.length > 1 ? 's' : ''} ${lines.slice(0, 4).join(', ')}${lines.length > 4 ? ` (+${lines.length - 4} more)` : ''}`);
    }
  }

  // 2. querySelector('.class') targets must exist.
  for (const [cls, lines] of classRefs) {
    if (ALLOWLIST.has(cls)) continue;
    if (!classes.has(cls)) {
      problems.push(`MISSING CLASS .${cls} — referenced at line${lines.length > 1 ? 's' : ''} ${lines.slice(0, 4).join(', ')}${lines.length > 4 ? ` (+${lines.length - 4} more)` : ''}`);
    }
  }

  // 3. Duplicate ids inside one page.
  for (const id of dupIds) {
    problems.push(`DUPLICATE ID id="${id}" appears on multiple elements`);
  }

  return { relPath, problems, stats: { ids: ids.size, classes: classes.size, idRefs: idRefs.size, classRefs: classRefs.size } };
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

function main() {
  const targets = (process.argv.slice(2).length > 0)
    ? process.argv.slice(2)
    : DEFAULT_GLOBS;

  const files = targets
    .map(t => path.resolve(REPO_ROOT, t))
    .filter(f => fs.existsSync(f) && fs.statSync(f).isFile());

  if (files.length === 0) {
    console.error('check-dom-refs: no HTML files found to check.');
    process.exit(1);
  }

  let failed = false;
  for (const file of files) {
    const { relPath, problems, stats } = checkPage(file);
    if (REDIRECT_STUBS.has(path.basename(file)) && problems.length === 0) {
      console.log(`✔ ${relPath} — redirect stub, no inline JS (clean)`);
      continue;
    }
    if (problems.length > 0) {
      failed = true;
      console.error(`✖ ${relPath} — ${problems.length} problem${problems.length > 1 ? 's' : ''}:`);
      problems.forEach(p => console.error(`    ${p}`));
    } else {
      console.log(`✔ ${relPath} — ${stats.idRefs} id refs, ${stats.classRefs} class refs, ${stats.ids} ids, ${stats.classes} classes (all resolve)`);
    }
  }

  if (failed) {
    console.error('\ncheck-dom-refs: FAILED — JS references DOM targets that do not exist in the markup.');
    process.exit(1);
  }
  console.log('\ncheck-dom-refs: all DOM references resolve.');
  process.exit(0);
}

main();
